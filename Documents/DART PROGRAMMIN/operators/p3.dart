void main (){

// Equality and relational operators in dart programming language
// Equality operator is used to check whether two values are equal or not and it will return a boolean value true or false.
var a = 10;
var b = 20;
print(a == b); // false
print('-----------------');
print(a != b); // true
// kya a b ke equal nahi hai , haa(true) a be ke equal nahi hai
print('-----------------');
// Relational operators are used to check whether one value is greater than, less than, greater than or equal to, less than or equal to another value and it will return a boolean value true or false.
print(a > b); // false
print('-----------------');
print(a < b); // true
print('-----------------');
print(a >= b); // false
print('-----------------');
print(a <= b); // true
















}